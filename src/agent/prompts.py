# agent/prompts.py — LLM에게 역할과 행동 규칙을 지시하는 시스템 프롬프트
#
# 역할: Gemini LLM이 대화를 시작할 때 가장 먼저 읽는 "행동 지침서".
#       LLM이 어떤 도구를 언제 써야 하는지, 답변 형식은 어떻게 해야 하는지,
#       무엇을 절대 하면 안 되는지를 명시한다.
#
# 왜 시스템 프롬프트가 중요한가?
#   - LLM은 기본적으로 "그럴듯한 답"을 생성하는 모델이라
#     출처 없이 있지도 않은 정보를 만들어낼 수 있다(환각, Hallucination).
#   - 이 프롬프트의 규칙들은 그런 환각을 최대한 막기 위한 가이드라인이다.
#   - "도구를 먼저 호출하고 그 결과만 바탕으로 답하라"는 규칙이 핵심.
